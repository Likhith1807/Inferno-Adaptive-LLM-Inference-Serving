#!/usr/bin/env python
"""
Generate docs/KERNEL_REPORT.md from measured data under docs/results/. Every number in the tables and every computed
sentence comes from those files; the prose around them describes what was tried and what is still unexplained.

    python scripts/sync_docs_results.py && python scripts/build_kernel_report.py
"""
import glob
import json
import statistics
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
R = ROOT / "docs" / "results"
LADDER = ["int4_v0_naive", "int4_v1_warp", "int4_v2_vec", "int4_v3_pad", "int4_v4_alg", "int4_v5_reuse", "int4_v6_lane16"]
CUSTOM_BEST = LADDER[3:]
BASELINES = ["cublas_fp16", "unfused_naive"]


def short(name):
    return name.split("(")[0].strip()


def jl(rel):
    p = R / rel
    return json.loads(p.read_text()) if p.exists() else None


def main():
    bench = jl("kernel_bench.json")
    shapes = bench["shapes"]
    by = [{k["kernel"]: k for k in s["kernels"]} for s in shapes]
    stream = bench.get("stream_read_gbps")
    all_correct = all(k["correct"] for s in shapes for k in s["kernels"])
    max_err = max(k["max_rel_err"] for s in shapes for k in s["kernels"])
    nruns = bench.get("n_runs", 1)

    def stable(k, s):
        """Large enough to be bandwidth-bound and, for every custom kernel and cuBLAS, at least 4 of the runs agree within 2%."""
        return s["int4_bytes"] > 5e6 and all(k[n].get("runs_within_2pct", nruns) >= min(4, nruns) for n in CUSTOM_BEST + ["cublas_fp16"])

    stable_idx = [i for i, (k, s) in enumerate(zip(by, shapes)) if stable(k, s)]

    L = []
    L.append("# Fused int4 GEMV kernel: measured results\n")
    L.append(f"Device: **{bench['device']}** (theoretical DRAM bandwidth {bench['peak_dram_gbps']:.0f} GB/s"
             + (f", measured streaming-read bandwidth {stream:.0f} GB/s = {100 * stream / bench['peak_dram_gbps']:.0f}% of theoretical" if stream else "")
             + f", L2 {bench['l2_mb']:.0f} MB). Every number below is the median of {nruns} independent benchmark "
             "invocations. Generated by `scripts/build_kernel_report.py` from `docs/results/`.\n")

    L.append("## What was built\n")
    L.append("A decode matvec `y = W_q x` with asymmetric group-wise int4 weights (group 128), fused so the fp16 weight matrix "
             "is never materialized. At batch 1 decode is memory-bound: runtime is set by bytes moved, so int4 should approach "
             "the byte ratio (about 3.76x with group-128 fp16 scales and zeros, not 4x) if the kernel saturates DRAM. The figures of "
             "merit are achieved bandwidth (against both the theoretical peak and the measured streaming-read bandwidth) and speedup "
             "against that byte-ratio ceiling.\n")
    L.append("Seven stages, each changing one thing (see `src/inferno/kernels/int4_gemv.cuh`, `int4_gemv_batch.cuh`):\n")
    L.append("| stage | change |\n|---|---|")
    L.append("| v0 | one thread per row (uncoalesced) |\n| v1 | one warp per row, coalesced 32-bit loads, shuffle reduce |")
    L.append("| v2 | 128-bit loads, activation vector staged in shared memory (predicted 16-way bank conflict: lanes fall on 2 of 32 banks) |")
    L.append("| v3 | v2 + one pad word per 32 activations (conflict-free) |")
    L.append("| v4 | v3 + algebraic form `s*(sum(q*x) - z*sum(x))`, streaming loads, 2 loads in flight |")
    L.append("| v5 | register reuse: decode the 32 weights of a chunk once into registers, read activations through the read-only cache (no shared-memory staging, no per-block prologue) |")
    L.append("| v6 | v5 with 16 lanes per row instead of 32 (K=1536 has 48 chunks per row: 32 lanes leave half of them with two chunks and half with one; 16 lanes give every lane exactly three) |\n")

    L.append("## Correctness\n")
    L.append(f"All kernels were checked against a double-precision CPU reference on every shape in every invocation "
             f"before any timing was trusted: **{'all correct' if all_correct else 'FAILURES PRESENT'}**, worst relative "
             f"error {max_err:.2e} (fp16 output rounding is ~5e-4). This gate mattered: the first version of v4 was "
             "flagged INCORRECT (relative error ~2-3) because it subtracted `z * sum(x over a whole 128-weight group)` "
             "once per 32-weight chunk, four times over; the bug was found and fixed only because timing was never "
             "reported for a kernel that failed the check. The kernel was additionally checked on the real Qwen2.5-1.5B-AWQ "
             "checkpoint inside vLLM (see the end-to-end section).\n")

    L.append("## Results by layer shape\n")
    L.append("Time in microseconds (median of invocation medians); `x cuBLAS` is the speedup over the fp16 cuBLAS GEMV; "
             "`%peak` is achieved DRAM bandwidth over theoretical, `%stream` over the measured streaming-read bandwidth; "
             "`agree` is how many of the runs lie within 2% of the reported median for the best kernel.\n")
    hdr = ["shape", "cuBLAS fp16", "unfused", "v0", "v1", "v2", "v3", "v4", "v5", "v6", "best", "best x cuBLAS", "ceiling", "%peak", "%stream", "agree"]
    L.append("| " + " | ".join(hdr) + " |\n|" + "|".join("---" for _ in hdr) + "|")
    for s, k in zip(shapes, by):
        best = min([k[n] for n in CUSTOM_BEST], key=lambda x: x["us_median"])
        ceil = (s["fp16_bytes"] + 2 * s["K"] + 2 * s["N"]) / (s["int4_bytes"] + 2 * s["K"] + 2 * s["N"])
        cells = [f"{short(s['name'])} {s['N']}x{s['K']}"] + [f"{k[n]['us_median']:.1f}" for n in BASELINES + LADDER] + \
                [best["kernel"].replace("int4_", ""), f"{k['cublas_fp16']['us_median'] / best['us_median']:.2f}x", f"{ceil:.2f}x",
                 f"{best['pct_peak']:.0f}%", f"{100 * best['gbps'] / stream:.0f}%" if stream else "n/a",
                 f"{best.get('runs_within_2pct', nruns)}/{nruns}"]
        L.append("| " + " | ".join(cells) + " |")
    L.append("\nThe two small layers (1-2 MB of weights, ~12-15 us kernels) are dominated by launch and clock jitter: their per-run "
             "medians scatter and differences between versions there are **not** meaningful. Conclusions below use only the large "
             "layers where at least 4 of 5 runs agree within 2% for every custom kernel. Where a single run out of five is an "
             "outlier (a laptop clock state), the median of five is still stable, and the `agree` column shows it.\n")

    L.append("## What each stage bought (large, stable layers)\n")
    for i in stable_idx:
        k, name = by[i], short(shapes[i]["name"])

        def chg(a, b):
            ta, tb = k[a]["us_median"], k[b]["us_median"]
            return f"{100 * (ta - tb) / ta:.1f}% faster" if tb < ta else f"{100 * (tb - ta) / ta:.1f}% slower"

        L.append(f"- **{name}**: v0 to v1 {k['int4_v0_naive']['us_median'] / k['int4_v1_warp']['us_median']:.1f}x faster (coalescing); "
                 f"v1 to v2 {chg('int4_v1_warp', 'int4_v2_vec')} (wider loads + shared-memory staging, with bank conflicts); "
                 f"v2 to v3 {chg('int4_v2_vec', 'int4_v3_pad')} (conflict-free padding); v3 to v4 {chg('int4_v3_pad', 'int4_v4_alg')} "
                 f"(algebraic form, streaming loads); v4 to v5 {chg('int4_v4_alg', 'int4_v5_reuse')} (register reuse, no smem staging); "
                 f"v5 to v6 {chg('int4_v5_reuse', 'int4_v6_lane16')} (16 lanes per row). "
                 f"Best: {max(k[n]['pct_peak'] for n in CUSTOM_BEST):.0f}% of theoretical peak bandwidth.")
    L.append("")

    # ------------------------------------------------------------ measurement notes
    L.append("## Measurement notes and a correction\n")
    fl = {}
    for f in sorted(glob.glob(str(R / "flush_sweep" / "*.json"))):
        d = json.loads(Path(f).read_text())
        name = Path(f).stem
        cub = name.startswith("cub_")
        mb = int(name.replace("cub_", "").split("_")[0].replace("mb", ""))
        fl.setdefault(mb, {"v5": [], "cublas": []})["cublas" if cub else "v5"].append(d["shapes"][0]["kernels"][0]["us_median"])
    if fl:
        L.append("**Weight-rotation size.** Each launch must stream its weights from DRAM, so the benchmark rotates through many "
                 "copies of them. The first version rotated through 192 MB (6x L2). Sweeping the footprint showed that this was "
                 "not enough: an L2 with non-LRU replacement keeps part of a cyclic working set, and a 23 MB kernel ran about 6% "
                 "too fast. Every earlier '% of peak' figure was inflated by that amount. The default is now 768 MB (24x L2).\n")
        L.append("| rotation footprint | v5 on llama7B_mlp_up (us, 3 runs) | cuBLAS fp16 (us, median of 3) |\n|---|---|---|")
        for mb in sorted(fl):
            L.append(f"| {mb} MB | {', '.join('%.1f' % v for v in fl[mb]['v5'])} | {statistics.median(fl[mb]['cublas']):.1f} |")
        L.append("")
    if stream:
        L.append(f"**Achievable bandwidth.** A read-only streaming kernel over a 512 MB buffer reaches {stream:.0f} GB/s "
                 f"({100 * stream / bench['peak_dram_gbps']:.1f}% of the {bench['peak_dram_gbps']:.0f} GB/s computed from the reported memory clock). "
                 "The table reports both denominators; the achievable figure is the honest ceiling for a read-bound kernel.\n")

    # ------------------------------------------------------------ small batch
    runs = [json.loads(Path(f).read_text()) for f in sorted(glob.glob(str(R / "kernel_batch_runs" / "run_*.json")))]
    if runs:
        L.append("## Small batches: where the CUDA-core kernel stops paying off\n")
        L.append(f"The same kernel decodes each weight chunk once and reuses it for B activation vectors (B = 1..16). Median of {len(runs)} "
                 "invocations against an fp16 cuBLAS GEMM with the same B. All results matched the CPU reference. The byte-ratio "
                 "ceiling includes the activation and output traffic for B vectors.\n")
        for si, s in enumerate(runs[0]["shapes"]):
            L.append(f"**{short(s['name'])}** ({s['N']}x{s['K']})\n")
            L.append("| B | cuBLAS fp16 us | custom us (16 lanes) | speedup | byte-ratio ceiling |\n|---|---|---|---|---|")
            for bi, b in enumerate(s["batches"]):
                cub = statistics.median(r["shapes"][si]["batches"][bi]["cublas_us"] for r in runs)
                l16 = statistics.median(r["shapes"][si]["batches"][bi]["int4_l16_us"] for r in runs)
                L.append(f"| {b['B']} | {cub:.1f} | {l16:.1f} | {cub / l16:.2f}x | {b['ceiling']:.2f}x |")
            L.append("")
        L.append("The advantage holds through B of about 4-6, break-even is around B = 7-8, and beyond that a CUDA-core kernel loses to "
                 "cuBLAS (tensor cores). This is the honest scope of the kernel: batch 1 and very small batches.\n")

    # ------------------------------------------------------------ in situ
    cmp_path = R / "kernel_comparison.md"
    if cmp_path.exists():
        L.append("## Against the kernels vLLM actually runs\n")
        L.append("Timed in situ with `torch.profiler` during decode of the AWQ Qwen2.5-1.5B model in vLLM 0.11, grouped by layer role; "
                 "same GPU, same shapes. The custom kernel is patched into vLLM's AWQ layers (`src/inferno/kernels/vllm_int4.py`).\n")
        L.append(cmp_path.read_text(encoding="utf-8"))
        insitu = {}
        for q in ("awq_marlin", "awq", "awq_inferno"):
            for mode in ("graphs", "eager"):
                d = jl(f"insitu/{q}_{mode}.json")
                if d and d.get("roles"):
                    insitu[(q, mode)] = {r: v["us_median"] for r, v in d["roles"].items()}
        if len(insitu) >= 4:
            L.append("\nSame kernels under both engine modes (in-situ median, us):\n")
            L.append("| path | mode | qkv | o_proj | gate_up | down | sum per layer |\n|---|---|---|---|---|---|---|")
            names = {"awq_marlin": "vLLM Marlin", "awq": "vLLM classic AWQ", "awq_inferno": "custom (v6)"}
            for (q, mode), v in sorted(insitu.items(), key=lambda kv: (kv[0][1] != "graphs", kv[0][0])):
                L.append(f"| {names[q]} | {mode} | " + " | ".join(f"{v[r]:.1f}" for r in ("qkv", "o_proj", "gate_up", "down")) + f" | {sum(v.values()):.1f} |")
            L.append("")
        slow = [(q, mode) for q in ("awq_marlin", "awq", "awq_inferno") for mode in ("graphs", "eager")
                if (jl(f"insitu/{q}_{mode}.json") or {}).get("slow_process_reps")]
        n_slow = sum(len(jl(f"insitu/{q}_{mode}.json")["slow_process_reps"]) for q, mode in slow)
        n_all = sum((jl(f"insitu/{q}_{mode}.json") or {}).get("n_process_reps", 0) for q in ("awq_marlin", "awq", "awq_inferno") for mode in ("graphs", "eager"))
        L.append("Reading this honestly:\n"
                 "- vLLM's Marlin kernel is at or near the bandwidth limit for the large layers at batch 1 on this GPU. The custom kernel is within roughly 15% of it on the large layers in CUDA-graph decode and about even on the small ones; it is faster than the classic AWQ kernel on every layer; it does **not** beat Marlin. End-to-end throughput (below) is the more reliable summary: parity at one sequence.\n"
                 "- **Correction.** An earlier version of this report claimed the custom kernel beat Marlin on all four layer shapes, from a Marlin timing about twice as slow as the values above. That timing cannot be reproduced: re-measuring Marlin in the same session in both eager and CUDA-graph mode gives the values in the table, and end-to-end throughput agrees with them. The earlier measurement is treated as invalid and its file has been retired.\n"
                 f"- **Likely cause of the bad sample.** {n_slow} of the {n_all} in-situ profiling processes run for this report had every kernel, FlashAttention included, running 2-5x slower than in sibling processes (a GPU-wide slowdown such as throttling). A single-process measurement taken during such an episode would look like the retracted one. This is why each in-situ time is the median of three fresh processes. It cannot be verified for the old run.\n"
                 "- In-situ times still vary between processes and between engine modes by more than the differences between the custom kernel and Marlin on some layers (see the ranges in `docs/results/insitu/*.json`), and the custom kernel's mode dependence (for example gate/up in eager vs graph mode) is larger than Marlin's and points the other way. The cause is not established; one hypothesis is that the custom kernel, which spends more instructions per weight, is more sensitive to SM clock and power state than a purely memory-bound kernel.\n")

    # ------------------------------------------------------------ e2e
    e2e = jl("e2e_kernel/summary.json")
    if e2e:
        L.append("## End to end inside vLLM\n")
        L.append("Decode throughput (output tokens/s) of Qwen2.5-1.5B-Instruct in vLLM 0.11 with CUDA-graph decode, one fresh process per "
                 "configuration and repetition, 256 output tokens per sequence, `ignore_eos`, greedy. Mean of per-repetition medians with a "
                 "95% t-interval; parentheses give the paired ratio to vLLM's default Marlin path.\n")
        md = (R / "e2e_kernel" / "summary.md")
        if md.exists():
            L.append(md.read_text(encoding="utf-8"))
        ag = e2e.get("text_agreement", {})
        if ag:
            L.append("\nGreedy-decoding agreement on the first prompt (identical leading tokens out of the total):\n")
            for k_, v in ag.items():
                L.append(f"- {k_}: {v['identical_prefix']} of {v['tokens']}" + (" (identical)" if v["identical_total"] else ""))
            L.append("")
        lc = next((c["layer_check"] for c in e2e["configs"].values() if c.get("layer_check")), None)
        if lc:
            L.append(f"Layer-level check on the loaded checkpoint: {lc['n_layers_checked']} patched linear layers, max relative error "
                     f"{lc['max_rel_err']:.2e} against vLLM's own dequantize-and-matmul.\n")
        L.append("Reading this honestly: at one sequence the custom kernel is at parity with vLLM's default Marlin path and ahead of the classic AWQ kernel "
                 "and fp16; with more concurrent sequences Marlin's tensor-core kernel is clearly faster. The kernel is a batch-1 result.\n")

    # ------------------------------------------------------------ dev log
    L.append("## Experiments that did not help (development log)\n")
    L.append("Single-invocation development measurements on the Qwen gate_up shape (17920x1536) unless noted; kept "
             "because negative results constrain the explanation.\n")
    L.append("- **v4 lost to v3 on the Qwen layers (K=1536, K=8960) but won on the Llama-7B shape (K=4096).** "
             "Hypotheses tested and rejected:\n"
             "  - *Streaming (evict-first) loads hurt short rows*: swapping to ordinary loads left gate_up unchanged "
             "(81.5 us vs 81 us) and made the K=4096 shape slower, so streaming loads are kept.\n"
             "  - *Per-block prologue*: a variant that precomputed per-chunk sums of x in shared memory was slower "
             "(85 us); parallelizing that prologue with warp shuffles was slower still (106 us), because a shuffle "
             "reduction is a chain of dependent ~25-cycle operations. Removing the prologue by accumulating sum(x) "
             "inside the main loop recovered most of the loss (81 us) but not all of it.\n"
             "  - *Late issue of scale/zero loads*: hoisting them to the top of the loop moved gate_up from 80.9 to "
             "79.7 us, within noise.\n"
             "- **What worked (v5, v6).** Dropping the shared-memory staging entirely (read activations through the read-only cache, decode "
             "each weight chunk once into registers) removed the K=1536 slowdown, and using 16 instead of 32 lanes per row helped the K=1536 layers a "
             "further 4-15% in the same invocation. That is consistent with the two candidate explanations (shared-memory prologue, lane imbalance for "
             "48-chunk rows), but no profiler counter has confirmed which one is responsible.\n"
             "- **Unrolling did not help.** Loading 2-6 chunks per lane before consuming them (more loads in flight) never beat one chunk per "
             "iteration once the lanes were balanced (`bench_int4_gemv --variants`).\n"
             "- **Still unexplained and unconfirmed:** the bank-conflict prediction for v2/v3 and the exact cause of the v4 slowdown. Separating "
             "them needs Nsight Compute counters (`make kernel-profile`), which require enabling GPU performance counters in the NVIDIA Control Panel on "
             "Windows (`ERR_NVGPUCTRPERM` otherwise; re-checked and still blocked). Until then these remain hypotheses.\n")

    L.append("## Limitations\n")
    L.append("- Batch 1 and very small batches only; above B of about 8 a tensor-core kernel is needed.\n"
             "- Measured on one laptop GPU (sm_89, 24 SMs, 256 GB/s). Numbers on other devices will differ; the "
             "`ARCH` variable in `src/inferno/kernels/Makefile` targets others.\n"
             "- Small layers are dominated by jitter; only large-layer conclusions are drawn.\n"
             "- In-situ times are kernel times only; the end-to-end section covers whole-token decode for one model on one GPU.\n"
             "- No Nsight counters (blocked by a Windows driver setting), so causal explanations are hypotheses.\n")
    L.append("## Reproduce\n")
    L.append("```bash\nsource scripts/toolchain_env.sh\nbash scripts/rerun_kernel_all.sh          # library, 5 ladder runs, 3 batch runs\n"
             "bash scripts/flush_sweep.sh                # rotation-size check\n"
             "bash scripts/insitu_graphs.sh              # in-situ kernel timing, both engine modes\n"
             "bash scripts/run_e2e_matrix.sh 3           # end-to-end decode matrix\n"
             "python scripts/compare_kernels.py && python -m inferno.experiments.report_e2e results/e2e_kernel docs/results/e2e_kernel\n"
             "python scripts/sync_docs_results.py && python scripts/build_kernel_report.py   # regenerates this file\n```\n")
    out = ROOT / "docs" / "KERNEL_REPORT.md"
    out.write_text("\n".join(L), encoding="utf-8")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
